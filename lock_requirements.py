#!/usr/bin/env python3
"""
lock_requirements.py - write requirements-<system>-<build>.lock: every package
installed in this environment, pinned to its exact version and to the SHA-256
hashes its index publishes for that version's wheels.

There's a lock per kind of machine, named after its operating system (each
pulls in a slightly different set of packages) and the PyTorch build it uses:
e.g. requirements-linux-cpu.lock (no NVIDIA GPU), requirements-windows-cu130.lock
(an NVIDIA GPU, CUDA 13.0) or requirements-macos-pypi.lock (macOS, where PyTorch
comes straight from PyPI). Make one on that kind of machine, after installing
from requirements.txt; see the README.

Installing from the lock with --require-hashes makes pip refuse any file that
isn't byte-for-byte one of those wheels, so a release replaced or tampered with
on PyPI after you locked it can't sneak in. Run it after deliberately
installing or upgrading something (and after checking the release has been out
for a week or so):

  yolo-env/bin/python lock_requirements.py               # e.g. requirements-linux-cpu.lock
  yolo-env/bin/python lock_requirements.py --torch cu130  # e.g. requirements-linux-cu130.lock
  yolo-env/bin/python lock_requirements.py --torch pypi   # requirements-macos-pypi.lock
(on Windows: yolo-env\\Scripts\\python lock_requirements.py ...)
"""

import argparse
import json
import re
import subprocess
import sys
import urllib.request

TORCH_INDEXES = "https://download.pytorch.org/whl"  # PyTorch's own builds: /cpu, /cu130...
HEADER = """\
# Generated by lock_requirements.py from the packages installed in yolo-env.
# Every package, with the hashes of its published wheels. Install with:
#
#   python3 -m venv yolo-env
#   yolo-env/bin/pip install --require-hashes --only-binary :all: \\
#       {index}-r {lock}
#
# (on Windows: yolo-env\\Scripts\\pip). requirements.txt lists just the
# packages the project uses directly; the README has the full setup.
"""


def wheel_hashes(name, version, torch_index):
    if "+" in version:  # a PyTorch build (+cpu, +cu130...) from its own index: the hash is in each link
        page = urllib.request.urlopen(f"{torch_index}/{name.lower()}/").read().decode()
        prefix = re.escape(f"{name.replace('-', '_')}-{version}".replace("+", "%2B"))
        return sorted(set(re.findall(rf'href="[^"]*/{prefix}-[^"#]*\.whl#sha256=([0-9a-f]{{64}})"', page)))
    data = json.load(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json"))
    return sorted({f["digests"]["sha256"] for f in data["urls"] if f["packagetype"] == "bdist_wheel"})


def main():
    p = argparse.ArgumentParser(description="pin every installed package, with hashes")
    p.add_argument("--torch", default="cpu",
                   help="the PyTorch build installed here, as in its index URL: cpu, cu130..., "
                        "or pypi for PyPI's own (macOS) (default: cpu)")
    args = p.parse_args()
    torch_index = None if args.torch == "pypi" else f"{TORCH_INDEXES}/{args.torch}"
    system = {"win32": "windows", "darwin": "macos"}.get(sys.platform, sys.platform.rstrip("0123456789"))
    lock = f"requirements-{system}-{args.torch}.lock"

    frozen = subprocess.run([sys.executable, "-m", "pip", "freeze", "--all", "--exclude-editable"],
                            capture_output=True, text=True, check=True).stdout
    pins = sorted((line.split("==") for line in frozen.splitlines()
                   if "==" in line and not line.startswith("pip==")), key=lambda p: p[0].lower())
    entries = []
    for name, version in pins:
        if "+" in version and (torch_index is None or not version.endswith(f"+{args.torch}")):
            sys.exit(f"{name}=={version} isn't the {args.torch} build: use --torch {version.split('+')[1]}")
        hashes = wheel_hashes(name, version, torch_index)
        if not hashes:
            sys.exit(f"No published wheel hashes for {name}=={version}; not writing the lock.")
        entries.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    with open(lock, "w") as f:
        index = f"--extra-index-url {torch_index} \\\n#       " if torch_index else ""
        f.write(HEADER.format(index=index, lock=lock) + "\n" + "\n".join(entries) + "\n")
    print(f"Wrote {lock}: {len(entries)} packages.")


if __name__ == "__main__":
    main()
